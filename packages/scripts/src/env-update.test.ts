import { afterEach, expect, test } from 'bun:test'
import { execFileSync } from 'node:child_process'
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'

const script = resolve(import.meta.dir, 'env-update.ts')
const directories: string[] = []

afterEach(() => {
  for (const directory of directories.splice(0)) {
    rmSync(directory, { recursive: true, force: true })
  }
})

test('preserves explicit workflow bindings per block while adding new keys', () => {
  const directory = mkdtempSync(join(tmpdir(), 'o-env-update-'))
  directories.push(directory)
  mkdirSync(join(directory, 'src'))
  mkdirSync(join(directory, '.github/workflows'), { recursive: true })
  writeFileSync(join(directory, 'package.json'), '{}')
  writeFileSync(
    join(directory, 'src/env.ts'),
    `export const production = {
      NEW_SERVICE_KEY: Symbol.for('take-out/env/expected'),
      UNCHANGED_KEY: Symbol.for('take-out/env/expected'),
      ADDED_KEY: Symbol.for('take-out/env/expected'),
    }
    export const versions = { ZERO_VERSION: '1.9.0' }
    `
  )

  const workflow = join(directory, '.github/workflows/deploy.yml')
  const initial = `jobs:
  production:
    env:
      # 🔒 start - this is generated by "bun env:update"
      NEW_SERVICE_KEY: \${{ secrets.DEPLOYED_SERVICE_KEY }}
      UNCHANGED_KEY: \${{ secrets.UNCHANGED_KEY }}
      ZERO_VERSION: \${{ secrets.ZERO_VERSION }}
      REMOVED_KEY: \${{ secrets.REMOVED_KEY }}
      # 🔒 end - this is generated by "bun env:update"
  staging:
    env:
      # 🔒 start - this is generated by "bun env:update"
      NEW_SERVICE_KEY: '\${{ secrets.STAGING_SERVICE_KEY }}' # explicit staging binding
      UNCHANGED_KEY: \${{ secrets.UNCHANGED_KEY }}
      # 🔒 end - this is generated by "bun env:update"
`
  writeFileSync(workflow, initial)

  const run = () => execFileSync(process.execPath, [script], { cwd: directory })
  run()
  const generated = readFileSync(workflow, 'utf8')
  const expected = initial
    .replaceAll(
      '      NEW_SERVICE_KEY:',
      '      ADDED_KEY: ${{ secrets.ADDED_KEY }}\n      NEW_SERVICE_KEY:'
    )
    .replace('ZERO_VERSION: ${{ secrets.ZERO_VERSION }}', "ZERO_VERSION: '1.9.0'")
    .replace('      REMOVED_KEY: ${{ secrets.REMOVED_KEY }}\n', '')
  // the version is generated in every block, including newly populated blocks.
  expect(generated).toBe(
    expected.replace(
      '      UNCHANGED_KEY: ${{ secrets.UNCHANGED_KEY }}\n      # 🔒 end',
      "      UNCHANGED_KEY: ${{ secrets.UNCHANGED_KEY }}\n      ZERO_VERSION: '1.9.0'\n      # 🔒 end"
    )
  )

  run()
  expect(readFileSync(workflow, 'utf8')).toBe(generated)
})
